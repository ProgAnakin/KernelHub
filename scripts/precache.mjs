import { createHash } from "node:crypto";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_MANIFEST = "precache-manifest.js";
const MAX_ASSETS = 512;

export function clearPrecache() {
  // A manifest from a previous normal build must never be copied into a fresh
  // static export. Each successful build generates its own dependency list.
  rmSync(join("public", GENERATED_MANIFEST), { force: true });
}

export function generatePrecache({
  staticDirectory = ".next/static",
  outputDirectory = "public",
} = {}) {
  const root = resolve(staticDirectory);
  const files = [];
  const visit = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isSymbolicLink())
        throw new Error("Offline assets must not contain symbolic links");
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && /\.(js|css)$/.test(entry.name))
        files.push(path);
    }
  };
  visit(root);
  const assets = files
    .map((path) => ({
      path,
      url: `_next/static/${relative(root, path).split(sep).join("/")}`,
    }))
    .sort((left, right) => left.url.localeCompare(right.url, "en"));
  if (!assets.length || assets.length > MAX_ASSETS)
    throw new Error(`Expected 1–${MAX_ASSETS} offline build assets`);
  const revision = createHash("sha256");
  for (const item of assets) {
    if (
      item.url.length > 512 ||
      !/^_next\/static\/[A-Za-z0-9_./-]+\.(js|css)$/.test(item.url) ||
      item.url.split("/").some((part) => part === "." || part === "..")
    )
      throw new Error("Unexpected offline asset path");
    revision.update(item.url).update("\0").update(readFileSync(item.path));
  }
  const manifest = {
    version: 1,
    revision: revision.digest("hex"),
    assets: assets.map((item) => item.url),
  };
  // The browser checks this imported script when updating the service worker.
  // A changed worker chunk therefore triggers installation even if sw.js itself
  // is unchanged. No TypeScript source maps or user data enter this manifest.
  writeFileSync(
    join(outputDirectory, GENERATED_MANIFEST),
    `/* Generated by scripts/precache.mjs; do not edit. */\nself.__KERNELHUB_PRECACHE = ${JSON.stringify(manifest)};\n`,
  );
  console.log(`Prepared offline cache for ${assets.length} build assets.`);
  return manifest;
}

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  if (process.argv.includes("--clean")) clearPrecache();
  else generatePrecache();
}
